# -*- coding: utf-8 -*-
"""发布 v2.23：采购明细区分「已到货登记」和「已收(已上架)」。"""
import os
import sys

REPO = r"C:\Users\Kerwin\Desktop\kuaimai发货查询"
INSTALLER = os.path.join(REPO, "packaging", "out", "快麦扫码查询_安装版_v2.23.exe")
NOTES = (
    "**v2.23：采购明细把「已到货登记」和「已收(已上架)」分开显示**\n"
    "\n"
    "**为什么要改**\n"
    "· ERP 的「已收」口径经实测确认 = **收货单里已上架的数量之和**：\n"
    "    单头 已收 1598 = Σ已上架 1598 （≠ Σ收货登记 3916）\n"
    "  6 张收货单里 5 张已上架、1 张还没上架（那 2318 件），所以已收只有 1598。\n"
    "· 也就是说：**货到了但还没上架，ERP 的「已收」就是 0** —— 这是 ERP 的规则，\n"
    "  不是程序算错。但只显示一个 0 容易让人以为没收到货。\n"
    "\n"
    "**这一版的做法：三个数字都摆出来**\n"
    "· 商品明细列改成：采购数量 / **已到货登记** / **已收(已上架)** / 待收 / 正品 / 次品\n"
    "    · 已到货登记 = 收货单登记的数量（含还没上架的）\n"
    "    · 已收(已上架) = 已上架的数量（= ERP 的「已收」口径）\n"
    "    · 待收 = 采购数量 − 已收(已上架)\n"
    "· 底部合计也一并列出。收货记录里「未完成」改叫「未上架」，更贴实际。\n"
    "\n"
    "**实测**（采购单 CG6056070037723603）\n"
    "  编码            采购   已到货登记  已收(已上架)   待收\n"
    "  9687-燕麦色M    1176      1176        715        461\n"
    "  9687-燕麦色L     784       784        222        562\n"
    "  9693-咖色M       210       210          0        210\n"
    "  合计：采购 3916　已到货 3916　已收(已上架) 1598　待收 2318　收货单 6 张(已上架 5)\n"
    "\n"
    "  这样一眼就能看出：货都登记到了（3916），但只上架了 1598，还剩 2318 没上架。\n"
)

assert os.path.isfile(INSTALLER), "安装包不存在：%s" % INSTALLER
sys.path.insert(0, REPO)
os.chdir(REPO)
sys.argv = ["release.py", "--version", "v2.23", "--installer", INSTALLER, "--notes", NOTES]

import release  # noqa: E402

rc = release.main()
print("\nrelease.main() returned", rc)
sys.exit(rc)
